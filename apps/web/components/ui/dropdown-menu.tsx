"use client";

import * as React from "react";
import { Menu as MenuPrimitive } from "@base-ui/react/menu";

import { cn } from "@/lib/utils";
import { ChevronRightIcon, CheckIcon } from "lucide-react";

// On a phone a menu is a sheet up from the bottom edge: the same rows, the
// width of the screen, under the thumb rather than beside it. Where it is
// put is the phone block of globals.css, which the positioner's own inline
// placing gives way to; the rest is here.
export const PHONE_SHEET =
  "max-sm:w-full max-sm:min-w-0 max-sm:max-h-[70dvh] max-sm:rounded-b-none max-sm:rounded-t-3xl max-sm:p-2 max-sm:pb-[calc(env(safe-area-inset-bottom)+8px)] max-sm:transition-[opacity,translate] max-sm:duration-base max-sm:data-starting-style:translate-y-8 max-sm:data-starting-style:scale-100 max-sm:data-starting-style:blur-[0px] max-sm:data-ending-style:duration-fast max-sm:data-ending-style:translate-y-8 max-sm:data-ending-style:scale-100 max-sm:data-ending-style:blur-[0px]";

function DropdownMenu({ ...props }: MenuPrimitive.Root.Props) {
  return <MenuPrimitive.Root data-slot="dropdown-menu" {...props} />;
}

function DropdownMenuPortal({ ...props }: MenuPrimitive.Portal.Props) {
  return <MenuPrimitive.Portal data-slot="dropdown-menu-portal" {...props} />;
}

function DropdownMenuTrigger({ ...props }: MenuPrimitive.Trigger.Props) {
  return <MenuPrimitive.Trigger data-slot="dropdown-menu-trigger" {...props} />;
}

function DropdownMenuContent({
  align = "start",
  alignOffset = 0,
  side = "bottom",
  sideOffset = 4,
  className,
  ...props
}: MenuPrimitive.Popup.Props &
  Pick<
    MenuPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset"
  >) {
  return (
    <MenuPrimitive.Portal>
      <MenuPrimitive.Backdrop className="fixed inset-0 z-40 max-sm:bg-black/20" />
      <MenuPrimitive.Positioner
        data-phone-sheet
        className="isolate z-50 outline-none"
        align={align}
        alignOffset={alignOffset}
        side={side}
        sideOffset={sideOffset}
      >
        <MenuPrimitive.Popup
          data-slot="dropdown-menu-content"
          className={cn(
            "glass-solid z-50 max-h-(--available-height) w-(--anchor-width) min-w-40 origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-2xl border-0 bg-popover p-2.5 text-popover-foreground shadow-dropdown outline-none transition-[opacity,scale,filter] duration-fast ease-out-quart data-starting-style:opacity-0 data-starting-style:scale-95 data-starting-style:blur-[2px] data-ending-style:duration-instant data-ending-style:ease-in-quad data-ending-style:opacity-0 data-ending-style:scale-95 data-ending-style:blur-[2px] data-ending-style:overflow-hidden",
            PHONE_SHEET,
            className,
          )}
          {...props}
        />
      </MenuPrimitive.Positioner>
    </MenuPrimitive.Portal>
  );
}

